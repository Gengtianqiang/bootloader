[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$InputBin,
    [Parameter(Mandatory = $true)][string]$OutputPackage
)

$ErrorActionPreference = 'Stop'
$inputPath = (Resolve-Path -LiteralPath $InputBin).ProviderPath
$outputPath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputPackage)
if ($inputPath -eq $outputPath) {
    throw 'Use a different output path for the encrypted package.'
}

$firmware = [IO.File]::ReadAllBytes($inputPath)
$appBase = 0x08008000
$appMax = 96KB - 16
if ($firmware.Length -lt 8 -or $firmware.Length -gt $appMax) {
    throw "App size must be between 8 and $appMax bytes."
}
$stackTop = [BitConverter]::ToUInt32($firmware, 0)
$resetVector = [BitConverter]::ToUInt32($firmware, 4)
$resetAddress = $resetVector - ($resetVector -band 1)
if ($stackTop -le 0x20000000 -or $stackTop -gt 0x20020000 -or ($stackTop % 8) -ne 0 -or
    ($resetVector -band 1) -eq 0 -or $resetAddress -lt ($appBase + 8) -or
    $resetAddress -ge ($appBase + $firmware.Length)) {
    throw 'Invalid App vectors. Use the otatest.bin generated by this App project''s App-Debug preset.'
}

# Step2 consumes only the length field in the 16-byte header. Pad the body
# with zeros to a full AES block and encrypt header and body in one chain.
$padded = [int]([Math]::Ceiling($firmware.Length / 16.0) * 16)
$plain = [byte[]]::new(16 + $padded)
[BitConverter]::GetBytes([uint32]$firmware.Length).CopyTo($plain, 12)
$firmware.CopyTo($plain, 16)

$aes = [Security.Cryptography.Aes]::Create()
try {
    $aes.Key = [Text.Encoding]::ASCII.GetBytes('12121212121212121212121212121212')
    $aes.IV = [Text.Encoding]::ASCII.GetBytes('1212121212121212')
    $aes.Mode = [Security.Cryptography.CipherMode]::CBC
    $aes.Padding = [Security.Cryptography.PaddingMode]::None
    $encryptor = $aes.CreateEncryptor()
    try {
        $cipher = $encryptor.TransformFinalBlock($plain, 0, $plain.Length)
        [IO.File]::WriteAllBytes($outputPath, $cipher)
    } finally {
        $encryptor.Dispose()
    }
} finally {
    $aes.Dispose()
}
Write-Output "$outputPath ($($cipher.Length) bytes, App $($firmware.Length) bytes)"
